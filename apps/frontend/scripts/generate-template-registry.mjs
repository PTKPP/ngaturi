import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const frontendRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const templatesRoot = join(frontendRoot, "src", "templates");
const outputPath = join(templatesRoot, "generated-registry.ts");
const directoryPattern = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
const packages = readdirSync(templatesRoot, { withFileTypes: true })
  .filter((entry) => entry.isDirectory() && directoryPattern.test(entry.name) && existsSync(join(templatesRoot, entry.name, "index.ts")) && existsSync(join(templatesRoot, entry.name, "manifest.ts")))
  .map((entry) => entry.name)
  .sort();

if (packages.length === 0) throw new Error("Tidak ada paket template yang ditemukan.");

const identifiers = packages.map((name) => name.replace(/-([a-z0-9])/g, (_, character) => character.toUpperCase()));
const generated = [
  "/* This file is generated by scripts/generate-template-registry.mjs. */",
  "/* Add a self-contained template folder, then run npm run templates:generate. */",
  ...packages.map((name, index) => `import { templateModule as ${identifiers[index]} } from "./${name}";`),
  "",
  `export const generatedTemplateModules = [${identifiers.join(", ")}] as const;`,
  "",
].join("\n");

if (process.argv.includes("--check")) {
  if (!existsSync(outputPath) || readFileSync(outputPath, "utf8") !== generated) {
    throw new Error("Registry template generated tidak sinkron. Jalankan npm run templates:generate.");
  }
} else if (!existsSync(outputPath) || readFileSync(outputPath, "utf8") !== generated) {
  writeFileSync(outputPath, generated, "utf8");
}
